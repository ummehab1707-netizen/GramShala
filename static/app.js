const LANGS = [
  ["en", "English"],
  ["hi", "हिन्दी"],
  ["te", "తెలుగు"],
];

function readJson(key) {
  try {
    return JSON.parse(localStorage.getItem(key) || "null");
  } catch (e) {
    return null;
  }
}

const state = {
  lang: localStorage.getItem("gs-lang") || "en",
  role: null,
  me: readJson("gs-me"),
  boot: null,
  ws: null,
  // quiz progress (student)
  answers: {},
  quizSaved: false,
  quizDone: false,
  // self-paced position (student)
  self: { lessonId: null, phase: "lobby", page: 0 },
};

const el = (html) => {
  const n = document.createElement("div");
  n.innerHTML = html.trim();
  return n.firstElementChild;
};

const esc = (s) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

const L = () => t[state.lang] || t.en;
const txt = (obj) => (obj && (obj[state.lang] || obj.en)) || "";
const lessonById = (id) => state.boot.lessons.find((l) => l.id === id) || state.boot.lessons[0];

function resetQuiz() {
  state.answers = {};
  state.quizSaved = false;
  state.quizDone = false;
}

async function api(path, body) {
  const res = await fetch(path, {
    method: body ? "POST" : "GET",
    headers: body ? { "Content-Type": "application/json" } : undefined,
    body: body ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) throw new Error(`${path} failed: ${res.status}`);
  return res.json();
}

function connectSocket() {
  if (state.ws && (state.ws.readyState === 0 || state.ws.readyState === 1)) return;
  const proto = location.protocol === "https:" ? "wss" : "ws";
  const ws = new WebSocket(`${proto}://${location.host}/ws`);
  state.ws = ws;
  ws.onopen = () => {
    ws.send(
      JSON.stringify({
        type: "hello",
        role: state.role || "guest",
        studentId: state.me?.studentId || (state.role === "teacher" ? "teacher-hub" : `guest-${Date.now()}`),
        name: state.me?.name || (state.role === "teacher" ? "Teacher" : "Guest"),
      })
    );
  };
  ws.onmessage = (ev) => {
    const msg = JSON.parse(ev.data);
    if (msg.type === "state") {
      Object.assign(state.boot, msg);
      // Only the teacher-led mode ties quiz progress to the hub's phase.
      if (state.role === "student" && msg.mode === "led" && msg.phase !== "quiz") resetQuiz();
      render();
    }
  };
  ws.onclose = () => {
    if (state.ws === ws) {
      state.ws = null;
      if (state.role) setTimeout(connectSocket, 1500);
    }
  };
}

function closeSocket() {
  if (state.ws) {
    const w = state.ws;
    state.ws = null;
    w.close();
  }
}

function render() {
  const root = document.getElementById("app");
  if (!state.boot) return;
  document.documentElement.lang = state.lang;
  if (!state.role) {
    root.replaceChildren(gate());
    return;
  }
  if (state.role === "teacher") root.replaceChildren(teacherView());
  else root.replaceChildren(studentView());
}

function topbar() {
  const bar = el(`
    <header class="topbar">
      <div class="brand">
        <div class="stamp">ग</div>
        <div>
          <h1>GramShala</h1>
          <p>${L().tag}</p>
        </div>
      </div>
      <div class="chip-row">
        ${LANGS.map(([c, n]) => `<button class="chip ${state.lang === c ? "on" : ""}" data-lang="${c}">${n}</button>`).join("")}
        ${state.role ? `<button class="chip" id="leave">${L().home}</button>` : ""}
      </div>
    </header>
  `);
  bar.querySelectorAll("[data-lang]").forEach((b) => {
    b.onclick = () => {
      state.lang = b.dataset.lang;
      localStorage.setItem("gs-lang", state.lang);
      render();
    };
  });
  const leave = bar.querySelector("#leave");
  if (leave) {
    leave.onclick = () => {
      closeSocket();
      state.role = null;
      render();
    };
  }
  return bar;
}

function gate() {
  const wrap = el(`<div></div>`);
  wrap.append(topbar());
  wrap.append(
    el(`
      <section class="hero">
        <p class="kicker">${L().kicker}</p>
        <h2>${L().heroTitle}</h2>
        <p>${L().heroBody}</p>
        <div class="roles">
          <button class="role" id="as-teacher"><h3>${L().teacher}</h3><p>${L().teacherHint}</p></button>
          <button class="role" id="as-student"><h3>${L().student}</h3><p>${L().studentHint}</p></button>
        </div>
      </section>
    `)
  );
  wrap.querySelector("#as-teacher").onclick = () => {
    state.role = "teacher";
    connectSocket();
    render();
  };
  wrap.querySelector("#as-student").onclick = () => {
    state.role = "student";
    render();
  };
  return wrap;
}

