function analyticsHtml() {
  const a = state.boot.analytics;
  if (!a || !a.count) return `<p class="muted">${L().noResults}</p>`;
  const subj = (id) => txt(lessonById(id).subject);
  const help = a.needHelp.length
    ? `<h4>${L().needHelp}</h4>` +
      a.needHelp
        .map((n) => `<div class="student"><strong>${esc(n.name)}</strong><span class="muted">${subj(n.lessonId)} · ${n.pct}%</span></div>`)
        .join("")
    : "";
  const missed = a.missed.length
    ? `<h4>${L().missed}</h4>` +
      a.missed
        .map((m) => {
          const q = lessonById(m.lessonId).quiz[m.q];
          return `<div class="missed"><p>${txt(q.q)}</p><span class="muted">${L().missedFmt(m.pct)}</span></div>`;
        })
        .join("")
    : "";
  const rows = a.results
    .map(
      (r) =>
        `<div class="student"><span><strong>${esc(r.name)}</strong> <span class="muted">${subj(r.lessonId)}</span></span><span class="muted">${r.score}/${r.total}</span></div>`
    )
    .join("");
  return `
    <div class="stat-row">
      <div class="stat"><b>${a.avg}%</b><span>${L().avg}</span></div>
      <div class="stat"><b>${a.count}</b><span>${L().quizzes}</span></div>
    </div>
    ${help}${missed}
    <h4>${L().results}</h4>${rows}
  `;
}

