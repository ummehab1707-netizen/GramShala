function selfLobby() {
  const card = el(`
    <section class="card">
      <p class="kicker">${esc(state.me.name)}</p>
      <h3>${L().pick}</h3>
      <div class="lessons"></div>
    </section>
  `);
  const box = card.querySelector(".lessons");
  state.boot.lessons.forEach((l) => {
    const b = el(`<button class="lesson-pick"><strong>${txt(l.title)}</strong><div class="muted">${txt(l.subject)} · ${l.minutes} ${L().min}</div></button>`);
    b.onclick = () => {
      state.self = { lessonId: l.id, phase: "lesson", page: 0 };
      resetQuiz();
      render();
    };
    box.append(b);
  });
  return card;
}

function studentView() {
  const wrap = el(`<div></div>`);
  wrap.append(topbar());
  if (!state.me) {
    const card = el(`
      <section class="card">
        <p class="kicker">GramShala</p>
        <h3>${L().joinTitle}</h3>
        <input class="field" id="name" maxlength="40" placeholder="Meera" />
        <button class="primary" id="go">${L().enter}</button>
      </section>
    `);
    card.querySelector("#go").onclick = async () => {
      const name = card.querySelector("#name").value.trim() || "Meera";
      state.me = await api("/api/join", { name });
      localStorage.setItem("gs-me", JSON.stringify(state.me));
      connectSocket();
      render();
    };
    wrap.append(card);
    return wrap;
  }
  connectSocket();

  if (state.boot.mode === "led") {
    if (state.boot.phase === "lobby") {
      wrap.append(el(`<section class="hero"><h2>${L().waiting}</h2><p>${esc(state.me.name)}</p></section>`));
    } else {
      wrap.append(classroomCard(lessonById(state.boot.lessonId), state.boot, "follow"));
    }
    return wrap;
  }

  if (state.self.phase === "lobby" || !state.self.lessonId) {
    wrap.append(selfLobby());
  } else {
    wrap.append(classroomCard(lessonById(state.self.lessonId), state.self, "self"));
  }
  return wrap;
}

function selfNav(action) {
  const s = state.self;
  const lesson = lessonById(s.lessonId);
  const toLobby = () => {
    state.self = { lessonId: null, phase: "lobby", page: 0 };
    resetQuiz();
  };
  if (action === "next") {
    if (s.phase === "lesson") {
      if (s.page < lesson.pages.length - 1) s.page += 1;
      else {
        s.phase = "quiz";
        resetQuiz();
      }
    } else toLobby();
  } else if (action === "prev") {
    if (s.phase === "quiz") {
      s.phase = "lesson";
      s.page = lesson.pages.length - 1;
    } else if (s.phase === "lesson" && s.page > 0) s.page -= 1;
    else toLobby();
  } else if (action === "quiz") {
    s.phase = "quiz";
    resetQuiz();
  } else if (action === "lobby") toLobby();
  render();
}

