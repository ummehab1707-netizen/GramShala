// mode: "teacher" (controls the hub), "self" (student moves alone), "follow" (student follows the hub)
function classroomCard(lesson, view, mode) {
  const pages = lesson.pages;
  const card = el(`<section class="card"></section>`);
  if (view.phase === "quiz") {
    card.append(quizBlock(lesson, mode));
    return card;
  }
  const idx = Math.min(view.page || 0, pages.length - 1);
  const page = pages[idx];
  const pct = Math.round(((idx + 1) / pages.length) * 100);
  const showHook = mode === "follow" || idx === 0;
  card.innerHTML = `
    <p class="kicker">${txt(lesson.subject)} · ${L().page} ${idx + 1}/${pages.length}</p>
    <h3>${txt(lesson.title)}</h3>
    <div class="progress-bar"><span style="width:${pct}%"></span></div>
    <div class="art ${page.art || ""}"></div>
    <p class="story">${txt(page.text)}</p>
    ${showHook ? `<p class="muted">${txt(lesson.hook)}</p>` : ""}
    ${mode === "follow" ? "" : navButtons()}
  `;
  if (mode !== "follow") bindNav(card, mode);
  return card;
}

function navButtons() {
  return `
    <div class="actions">
      <button class="ghost" data-nav="prev">${L().back}</button>
      <button class="primary" data-nav="next">${L().next}</button>
      <button class="ghost" data-nav="quiz">${L().quiz}</button>
      <button class="ghost" data-nav="lobby">${L().lobby}</button>
    </div>
  `;
}

function bindNav(node, mode) {
  node.querySelectorAll("[data-nav]").forEach((btn) => {
    btn.onclick = () => (mode === "teacher" ? api("/api/control", { action: btn.dataset.nav }) : selfNav(btn.dataset.nav));
  });
}

// Stable per-student shuffle so the right answer is not always the first button.
function choiceOrder(lesson, qi, n, mode) {
  const idx = [...Array(n).keys()];
  if (mode === "teacher") return idx;
  const key = `${state.me?.studentId || "x"}|${lesson.id}|${qi}`;
  let h = 2166136261;
  for (let i = 0; i < key.length; i++) {
    h ^= key.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  for (let i = n - 1; i > 0; i--) {
    h = (Math.imul(h, 1664525) + 1013904223) >>> 0;
    const j = h % (i + 1);
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  return idx;
}

function scoreOf(lesson) {
  return lesson.quiz.reduce((n, q, i) => n + (state.answers[i] === q.answer ? 1 : 0), 0);
}

function quizBlock(lesson, mode) {
  const box = el(`<div></div>`);
  box.innerHTML = `<p class="kicker">${txt(lesson.subject)}</p><h3>${txt(lesson.title)}</h3>`;
  const interactive = mode !== "teacher";

  if (interactive && state.quizDone) {
    box.append(el(`<p class="story">${L().score}: ${scoreOf(lesson)}/${lesson.quiz.length}</p>`));
    if (mode === "self") {
      box.append(el(`<div class="actions"><button class="primary" data-nav="lobby">${L().lobby}</button></div>`));
      bindNav(box, mode);
    }
    return box;
  }

  lesson.quiz.forEach((q, qi) => {
    const item = el(`<div class="qitem"><p class="story">${txt(q.q)}</p></div>`);
    const labels = q.choices[state.lang] || q.choices.en;
    choiceOrder(lesson, qi, labels.length, mode).forEach((orig) => {
      const b = el(`<button class="choice">${labels[orig]}</button>`);
      if (!interactive) {
        if (orig === q.answer) b.classList.add("ok"); // teacher preview shows the answer
      } else {
        const chosen = state.answers[qi];
        if (chosen !== undefined) {
          if (orig === chosen) b.classList.add(orig === q.answer ? "ok" : "bad");
          else if (orig === q.answer) b.classList.add("ok");
        }
        b.onclick = () => {
          if (state.answers[qi] !== undefined) return;
          state.answers[qi] = orig;
          if (Object.keys(state.answers).length === lesson.quiz.length) finishQuiz(lesson);
          render();
        };
      }
      item.append(b);
    });
    box.append(item);
  });

  if (interactive && state.quizSaved) {
    const done = el(`<div class="actions"><button class="primary" id="see">${L().seeScore}</button></div>`);
    done.querySelector("#see").onclick = () => {
      state.quizDone = true;
      render();
    };
    box.append(done);
  }
  if (!interactive) {
    box.append(el(navButtons()));
    bindNav(box, mode);
  } else if (mode === "self") {
    box.append(el(`<div class="actions" style="margin-top:12px"><button class="ghost" data-nav="prev">${L().back}</button><button class="ghost" data-nav="lobby">${L().lobby}</button></div>`));
    bindNav(box, mode);
  }
  return box;
}

async function finishQuiz(lesson) {
  state.quizSaved = true;
  if (!state.me?.studentId) return;
  try {
    await api("/api/attempt", {
      studentId: state.me.studentId,
      name: state.me.name,
      lessonId: lesson.id,
      score: scoreOf(lesson),
      total: lesson.quiz.length,
      answers: lesson.quiz.map((_, i) => state.answers[i]),
    });
  } catch (e) {
    console.error(e);
  }
}

